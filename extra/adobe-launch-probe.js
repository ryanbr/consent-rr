        try {
            const now = w._satellite && w._satellite.getVar;
            const nowKeys = Object.keys(w._satellite || {});
            const only = (a, b) => {
                const names = a.filter(k => b.includes(k) === false);
                return names.length <= 8
                    ? names.join(',')
                    : names.slice(0, 8).join(',') + ' and ' +
                        (names.length - 8) + ' more';
            };
            // Which members, not just how many. A real library that
            // hydrates over this one is the only census of their
            // surface that comes from a live page rather than a
            // bundled copy, and a name on their side that is missing
            // here is the next thing a page can call and not find.
            const theirs = only(nowKeys, ourKeys);
            const mine = only(ourKeys, nowKeys);
            // Built as a list and not as arguments with two that
            // may be empty: say() joins on a space, so an absent one
            // left trailing whitespace on every line of the common
            // case, where the two surfaces match exactly.
            const parts = [ '_satellite at load is',
                now === undefined ? 'gone' :
                    now === ours ? 'still this replacement' :
                        'a real library, hydrated over it',
                '| members', nowKeys.length ];
            if ( theirs !== '' ) { parts.push('| theirs only:', theirs); }
            if ( mine !== '' ) { parts.push('| ours only:', mine); }
            say(...parts);
        } catch ( ex ) { }
        // What has not come back yet. A page that stops halfway is
        // usually waiting on one of these, and nothing else in a
        // console says which, because a request that never settles
        // prints nothing at all. But load is too early to accuse one:
        // a product search still in flight here finished a moment
        // later and was reported as never settling, so the verdict
        // waits five seconds and only then names what is stuck.
        const atLoad = [];
        pending.forEach((what, id) => atLoad.push(id));
        if ( atLoad.length !== 0 ) {
            const show = atLoad.map(id => pending.get(id));
            // Pushed, not passed: say() joins on a space, so an
            // empty tail argument leaves the line trailing one.
            const parts = [ 'in flight at load:', atLoad.length, '-',
                show.slice(0, 8).join(' | ') ];
            if ( show.length > 8 ) {
                parts.push('and', show.length - 8, 'more');
            }
            say(...parts);
            w.setTimeout(( ) => {
                const stuck = atLoad.filter(id => pending.has(id));
                if ( stuck.length === 0 ) {
                    say('all', atLoad.length,
                        'settled within 5s of load - none was stuck');
                    return;
                }
                const names = stuck.map(id => pending.get(id));
                const late = [ 'STILL PENDING 5s after load:',
                    stuck.length, 'of', atLoad.length, '-',
                    names.slice(0, 8).join(' | ') ];
                if ( names.length > 8 ) {
                    late.push('and', names.length - 8, 'more');
                }
                say(...late);
            }, 5000);
        }
